import type { GeoGebraEngine } from '../../../src/features/geogebra/types';
import { executeCommandPipeline } from '../../../src/features/geogebra/commands/commandPipeline';
import { isInternalHelperName } from '../../../src/features/geogebra/commands/custom/internalHelpers';
import { InternalHelperLifecycle } from '../../../src/features/geogebra/commands/custom/helperLifecycle';

/** Disposable engine probe for native history, deletion, and serialized dependencies. */
export const verifyNamedLifecycle = async (engine: GeoGebraEngine, report: (message: string) => void) => {
  const api = (name: string, ...args: unknown[]) => engine.callApi(name, args);
  const counts = async () => {
    const names = await api('getAllObjectNames') as string[];
    return { helpers: names.filter(isInternalHelperName).length, output: names.includes('out'), names };
  };
  await api('newConstruction');
  await engine.executeCommand('f:x+y=2\ng:2x-y=1\nh:x-2y=1\nj:3x+y=2\nk:x+3y=2');
  const failed = await executeCommandPipeline(engine, 'broken=Conic(f,g,h,j,k)+DefinitelyNotAGeoGebraCommand(1)', { allowNonGeometricHelpers: true });
  const afterFailure = await counts();
  report(`Failed command success=${failed.success}; labels=${failed.labels.join(',')}; helpers=${afterFailure.helpers}; broken=${afterFailure.names.includes('broken')}`);
  if (failed.success || afterFailure.helpers || afterFailure.names.includes('broken')) throw new Error('Failed command left construction objects');
  await api('setUndoPoint');
  const result = await executeCommandPipeline(engine, 'out=Conic(f,g,h,j,k)', { allowNonGeometricHelpers: true });
  if (!result.success) throw new Error(result.error);
  const created = await counts();
  const first = created.names.find(isInternalHelperName)!;
  report(`Created ${JSON.stringify({ helpers: created.helpers, output: created.output })}`);
  report(`First helper type ${await api('getObjectType', first)}; command ${String(await api('getCommandString', first)).slice(0, 120)}; definition ${String(await api('getDefinitionString', first)).slice(0, 120)}`);
  report(`Output definition ${String(await api('getDefinitionString', 'out')).slice(0, 220)}`);
  const xml = String(await api('getXML'));
  report(`XML helper ${xml.slice(Math.max(0, xml.indexOf(first) - 100), xml.indexOf(first) + 450).replace(/\s+/gu, ' ').slice(0, 550)}`);
  await api('setUndoPoint');
  await api('undo');
  const undone = await counts();
  report(`Undo ${JSON.stringify({ helpers: undone.helpers, output: undone.output })}`);
  await api('redo');
  const redone = await counts();
  report(`Redo ${JSON.stringify({ helpers: redone.helpers, output: redone.output })}`);
  const exported = await engine.exportGgb();
  await engine.importGgb(new File([exported], 'named-lifecycle.ggb'));
  const reopened = await counts();
  report(`Reopen ${JSON.stringify({ helpers: reopened.helpers, output: reopened.output })}`);
  await engine.executeCommand(`userValue=${first}+1`);
  await api('deleteObject', 'out');
  const deleted = await counts();
  report(`Delete output ${JSON.stringify({ helpers: deleted.helpers, output: deleted.output })}`);
  const lifecycle = new InternalHelperLifecycle(engine);
  await lifecycle.reconcile();
  const protectedNames = await counts();
  report(`User reference ${JSON.stringify({ helpers: protectedNames.helpers, output: protectedNames.output })}`);
  await api('deleteObject', 'userValue');
  await lifecycle.reconcile();
  const cleaned = await counts();
  report(`Cleanup ${JSON.stringify({ helpers: cleaned.helpers, output: cleaned.output })}`);
  await api('setUndoPoint');
  await api('undo');
  const restored = await counts();
  report(`Undo cleanup ${JSON.stringify({ helpers: restored.helpers, output: restored.output })}`);
  lifecycle.dispose();
  await api('newConstruction');
  await engine.executeCommand('f:x+y=2\ng:2x-y=1\nh:x-2y=1\nj:3x+y=2\nk:x+3y=2');
  const unnamed = await executeCommandPipeline(engine, 'Conic(f,g,h,j,k)', { allowNonGeometricHelpers: true });
  report(`Unnamed success=${unnamed.success}; labels=${unnamed.labels.join(',')}`);
  if (!unnamed.success || unnamed.labels.length !== 1 || isInternalHelperName(unnamed.labels[0])) throw new Error('Unnamed output was not reported');
};
