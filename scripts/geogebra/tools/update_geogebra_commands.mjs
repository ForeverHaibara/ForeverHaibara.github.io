import { writeFile } from 'node:fs/promises';

// Store command names locally so completion never depends on a network request.
const source = 'https://geogebra.github.io/docs/manual/en/commands/All_Commands/';
const response = await fetch(source);
if (!response.ok) throw new Error(`GeoGebra command index: HTTP ${response.status}`);
const html = await response.text();
const article = html.match(/<article class="doc">([\s\S]*?)<\/article>/)?.[1];
if (!article) throw new Error('GeoGebra command index has an unexpected layout.');
const names = [...new Set([...article.matchAll(/<a href="\.\.\/[^"/]+\/" class="xref page">([A-Za-z][A-Za-z0-9]*)<\/a>/g)].map((match) => match[1]))].sort();
if (names.length < 300) throw new Error(`Refusing to replace the catalog with only ${names.length} commands.`);
const output = `// Generated by scripts/geogebra/tools/update_geogebra_commands.mjs; do not edit manually.\n// Command-name index: ${source}\nexport const GEOGEBRA_COMMAND_NAMES: readonly string[] = ${JSON.stringify(names, null, 2)};\n`;
await writeFile(new URL('../../../src/features/geogebra/commands/completion/geogebraCommandNames.ts', import.meta.url), output);
console.log(`Updated ${names.length} GeoGebra command names.`);
